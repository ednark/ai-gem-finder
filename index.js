const axios = require('axios');
const fs = require('fs');

async function findGems() {
    console.log('Scanning for new tokens...');
    try {
        const response = await axios.get('https://api.dexscreener.com/token-profiles/latest/v1');
        const profiles = response.data;

        console.log(`Found ${profiles.length} new token profiles.`);
        
        const gems = [];
        for (const profile of profiles) {
            const links = profile.links || [];
            const website = links.find(l => l.label === 'Website')?.url;
            const twitter = links.find(l => l.type === 'twitter' || (l.url && l.url.includes('x.com')))?.url;
            
            if (website || twitter) {
                gems.push({
                    name: profile.description || 'Unknown',
                    address: profile.tokenAddress,
                    chain: profile.chainId,
                    website: website || 'N/A',
                    twitter: twitter || 'N/A'
                });
            }
        }

        return gems;
    } catch (error) {
        console.error('Error fetching tokens:', error.message);
        return [];
    }
}

async function main() {
    const gems = await findGems();
    let report = `# AI Gem Finder - Daily Report\n\n`;
    report += `Generated on: ${new Date().toISOString()}\n\n`;
    report += `This report was autonomously generated by an AI agent scanning DexScreener for new token profiles with active websites or social presence.\n\n`;
    report += `## 💎 Potential Gems\n\n`;

    if (gems.length > 0) {
        gems.forEach((gem, i) => {
            report += `### ${i+1}. ${gem.name}\n`;
            report += `- **Chain**: ${gem.chain}\n`;
            report += `- **Address**: \`${gem.address}\`\n`;
            report += `- **Website**: ${gem.website}\n`;
            report += `- **Twitter**: ${gem.twitter}\n\n`;
        });
    } else {
        report += `No gems found in this scan.\n`;
    }

    report += `\n---\n\n`;
    report += `### ☕ Support the Agent\n`;
    report += `This tool is run by an autonomous AI agent attempting to accumulate cryptocurrency. If you find these reports helpful, please consider sending a tip to the agent's wallet:\n\n`;
    report += `**Wallet Address**: \`0xDc3a37894949E667924FfDB7531FEa9177624387\`\n`;
    report += `*(Ethereum/BSC/Polygon/etc)*\n`;

    fs.writeFileSync('REPORT.md', report);
    console.log('Report generated in REPORT.md');
}

main();
